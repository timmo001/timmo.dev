// Solves src/theme/timmo.json into light, dark and Darker and writes
// src/styles/theme.generated.css, so the Worker never solves a theme at
// request time. Fails when a role misses its contrast target. Run with
// `aube run theme:gen` after changing the theme. It runs on Bun, since the
// tokens package ships TypeScript that Node won't strip in node_modules.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parseTheme, runtimeTheme } from "@timmo001/groundwork-tokens/runtime";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const parsed = parseTheme(
  await readFile(path.join(root, "src", "theme", "timmo.json"), "utf8"),
);

if (parsed._tag === "Failure") {
  throw new Error(`src/theme/timmo.json isn't a theme: ${String(parsed.failure)}`);
}

const { css, checks } = runtimeTheme(parsed.success);

const misses = checks.filter((result) => !result.passes);

if (misses.length > 0) {
  for (const miss of misses) {
    console.error(`${miss.role} in ${miss.mode}: ${miss.ratio.toFixed(2)}`);
  }

  process.exit(1);
}

await writeFile(
  path.join(root, "src", "styles", "theme.generated.css"),
  `/* Generated by scripts/build-theme.ts from src/theme/timmo.json. Don't edit. */\n${css}`,
);

console.log(`Wrote the Timmo theme: all ${checks.length} contrast checks pass`);
