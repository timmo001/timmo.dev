// Solves src/theme/timmo.json into light, dark and Darker and writes
// src/styles/theme.generated.css, so the Worker never solves a theme at
// request time, and src/generated/timmo-palette.ts, the dark roles as hex for
// the SVG README cards. Fails when a role misses its contrast target. Run
// with `aube run theme:gen` after changing the theme. It runs on Bun, since
// the tokens package ships TypeScript that Node won't strip in node_modules.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parseTheme, runtimeTheme } from "@timmo001/groundwork-tokens/runtime";

type Oklch = { readonly l: number; readonly c: number; readonly h: number };

// OKLCH to sRGB hex, through OKLab and linear sRGB. The solver keeps every
// role inside sRGB, so clamping only absorbs rounding
function toHex({ l, c, h }: Oklch): string {
  const angle = (h * Math.PI) / 180;
  const [a, b] = [c * Math.cos(angle), c * Math.sin(angle)];

  const lms = [
    (l + 0.3963377774 * a + 0.2158037573 * b) ** 3,
    (l - 0.1055613458 * a - 0.0638541728 * b) ** 3,
    (l - 0.0894841775 * a - 1.291485548 * b) ** 3,
  ] as const;

  const linear = [
    4.0767416621 * lms[0] - 3.3077115913 * lms[1] + 0.2309699292 * lms[2],
    -1.2684380046 * lms[0] + 2.6097574011 * lms[1] - 0.3413193965 * lms[2],
    -0.0041960863 * lms[0] - 0.7034186147 * lms[1] + 1.707614701 * lms[2],
  ];

  return `#${linear
    .map((channel) => {
      const value =
        channel <= 0.0031308
          ? 12.92 * channel
          : 1.055 * channel ** (1 / 2.4) - 0.055;

      return Math.round(Math.min(1, Math.max(0, value)) * 255)
        .toString(16)
        .padStart(2, "0");
    })
    .join("")}`;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const parsed = parseTheme(
  await readFile(path.join(root, "src", "theme", "timmo.json"), "utf8"),
);

if (parsed._tag === "Failure") {
  throw new Error(`src/theme/timmo.json isn't a theme: ${String(parsed.failure)}`);
}

const { css, checks, theme } = runtimeTheme(parsed.success);

const misses = checks.filter((result) => !result.passes);

if (misses.length > 0) {
  for (const miss of misses) {
    console.error(`${miss.role} in ${miss.mode}: ${miss.ratio.toFixed(2)}`);
  }

  process.exit(1);
}

await writeFile(
  path.join(root, "src", "styles", "theme.generated.css"),
  `/* Generated by scripts/build-theme.ts from src/theme/timmo.json. Don't edit. */\n${css}`,
);

const dark = theme.modes.dark;

if (dark === undefined) {
  throw new Error("The Timmo theme has no dark mode to draw the cards from");
}

const role = (name: string): Oklch => {
  const value = dark[name];

  if (value === undefined) {
    throw new Error(`The Timmo theme's dark mode has no ${name} role`);
  }

  return value;
};

// color-mix(in oklab, from amount%, to): the same mix the site's CSS uses
const mix = (from: Oklch, amount: number, to: Oklch): Oklch => {
  const lab = ({ l, c, h }: Oklch) => {
    const angle = (h * Math.PI) / 180;

    return { l, a: c * Math.cos(angle), b: c * Math.sin(angle) };
  };

  const [x, y] = [lab(from), lab(to)];
  const blend = (p: number, q: number) => p * amount + q * (1 - amount);
  const [l, a, b] = [blend(x.l, y.l), blend(x.a, y.a), blend(x.b, y.b)];

  return {
    l,
    c: Math.hypot(a, b),
    h: ((Math.atan2(b, a) * 180) / Math.PI + 360) % 360,
  };
};

const surface = role("surface-default");
const accent = role("accent");
const warning = role("warning");

const palette = {
  background: toHex(role("surface-lower")),
  surface: toHex(surface),
  surfaceRaised: toHex(role("surface-raised")),
  border: toHex(role("border-normal")),
  borderSoft: toHex(role("border-quiet")),
  text: toHex(role("text-strong")),
  textMuted: toHex(role("text-secondary")),
  textFaint: toHex(role("text-disabled")),
  accent: toHex(accent),
  accentSoft: toHex(role("fill-accent-hovered")),
  warning: toHex(warning),
  warningFill: toHex(mix(warning, 0.14, surface)),
  calendar: [
    toHex(role("fill-neutral-resting")),
    ...[0.25, 0.5, 0.75].map((amount) => toHex(mix(accent, amount, surface))),
    toHex(accent),
  ],
};

await writeFile(
  path.join(root, "src", "generated", "timmo-palette.ts"),
  `// Generated by scripts/build-theme.ts from src/theme/timmo.json. Don't edit.
// The Timmo theme's dark roles as sRGB hex, for the SVG README cards.
export const palette = ${JSON.stringify(palette, null, 2)} as const;
`,
);

console.log(`Wrote the Timmo theme: all ${checks.length} contrast checks pass`);
