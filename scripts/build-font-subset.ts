// Subsets Geist for the GitHub profile cards and writes
// src/generated/geist-subset.ts: a base64 woff2 per weight plus the advance
// width of every glyph, so the cards can embed the font and wrap text
// without a browser. Run with `pnpm font:subset` after changing the font or
// the character set.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { create as createFont } from "fontkit";
import subsetFont from "subset-font";

const WEIGHTS = [400, 600] as const;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const source = await readFile(
  path.join(root, "public", "fonts", "Geist-Variable.woff2"),
);

const ascii = Array.from({ length: 95 }, (_, index) =>
  String.fromCharCode(32 + index),
).join("");

const extras = "£€→←•·–—…’‘“”°×";

const characters = `${ascii}${extras}`;

type WeightEntry = {
  weight: number;
  woff2: string;
  widths: Record<string, number>;
};

const entries: Array<WeightEntry> = [];

for (const weight of WEIGHTS) {
  const [woff2, sfnt] = await Promise.all([
    subsetFont(source, characters, {
      targetFormat: "woff2",
      variationAxes: { wght: weight },
    }),
    subsetFont(source, characters, {
      targetFormat: "sfnt",
      variationAxes: { wght: weight },
    }),
  ]);

  const font = createFont(sfnt);

  const widths: Record<string, number> = {};

  for (const character of characters) {
    const run = font.layout(character);

    widths[character] =
      Math.round((run.advanceWidth / font.unitsPerEm) * 1000) / 1000;
  }

  entries.push({ weight, woff2: woff2.toString("base64"), widths });
}

const output = `// Generated by scripts/build-font-subset.ts. Do not edit by hand.
// Geist, subset to ${characters.length} characters, instanced at ${WEIGHTS.join(" and ")}.

export type GeistWeight = ${WEIGHTS.join(" | ")};

export const GEIST_FACES: Record<GeistWeight, string> = {
${entries.map(({ weight, woff2 }) => `  ${weight}:\n    "${woff2}",`).join("\n")}
};

export const GEIST_WIDTHS: Record<GeistWeight, Record<string, number>> = {
${entries
  .map(({ weight, widths }) => `  ${weight}: ${JSON.stringify(widths)},`)
  .join("\n")}
};
`;

const target = path.join(root, "src", "generated", "geist-subset.ts");

await mkdir(path.dirname(target), { recursive: true });

await writeFile(target, output);

console.log(
  `Wrote ${path.relative(root, target)} (${entries.map(({ weight, woff2 }) => `${weight}: ${Math.round(woff2.length / 1024)} KiB`).join(", ")})`,
);
