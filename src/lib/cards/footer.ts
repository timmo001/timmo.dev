import { format } from "date-fns";

import {
  CARD_WIDTH,
  type CardSpec,
  card,
  escapeXml,
  palette,
} from "~/lib/cards/theme";

export type FooterCardInput = {
  updatedAt: Date;
  source: string;
};

export function footerCard(input: FooterCardInput): CardSpec {
  const updated = `${format(input.updatedAt, "d MMM yyyy, HH:mm")} UTC`;

  return card({
    width: CARD_WIDTH,
    height: 44,
    title: "Generated by timmo.dev",
    description: `Cards generated by timmo.dev, updated ${updated}. Source: ${input.source}.`,
    fill: palette.surface,
    css: `.footer{font-size:11.5px;fill:${palette.textFaint}}
.footer-strong{fill:${palette.textMuted};font-weight:600}`,
    body: (box) =>
      `<text class="footer" x="${box.x + box.width / 2}" y="${box.y + box.height / 2 + 4}" text-anchor="middle">Generated by <tspan class="footer-strong">timmo.dev</tspan>  ·  Updated ${escapeXml(updated)}  ·  Source <tspan class="footer-strong">${escapeXml(input.source)}</tspan></text>`,
  });
}
